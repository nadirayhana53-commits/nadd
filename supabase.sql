-- Berikan hak sequence untuk kolom ID otomatis, jika sequence tersedia.
DO $$
DECLARE seq_name TEXT;
BEGIN
  seq_name := pg_get_serial_sequence('public.tasks','id');
  IF seq_name IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO anon, authenticated', seq_name);
  END IF;
  seq_name := pg_get_serial_sequence('public.courses','id');
  IF seq_name IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO anon, authenticated', seq_name);
  END IF;
END $$;

