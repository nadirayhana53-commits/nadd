-- Jika user_id berasal dari versi login lama, izinkan NULL tanpa error jika kolom tidak ada.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='public' AND table_name='tasks' AND column_name='user_id'
  ) THEN
    ALTER TABLE public.tasks ALTER COLUMN user_id DROP NOT NULL;
  END IF;
END $$;

UPDATE public.tasks SET status='pending' WHERE status IS NULL;
UPDATE public.tasks SET priority='normal' WHERE priority IS NULL;
ALTER TABLE public.tasks ALTER COLUMN status SET DEFAULT 'pending';
ALTER TABLE public.tasks ALTER COLUMN priority SET DEFAULT 'normal';

